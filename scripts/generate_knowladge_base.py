def main():
    KNOWLEDGE_DIR.mkdir(parents=True, exist_ok=True)

    created = 0
    for name, content in DOCUMENTS.items():
        path = KNOWLEDGE_DIR / f"demo_{name}.txt"
        if path.exists():
            print(f"跳过已存在文件：{path.name}")
            continue

        path.write_text(content.strip() + "\n", encoding="utf-8")
        created += 1

    files = sorted(KNOWLEDGE_DIR.glob("*.txt"))
    total_chars = sum(
        len(path.read_text(encoding="utf-8"))
        for path in files
    )

    print(f"本次新建文档：{created}")
    print(f"知识库 TXT 文档总数：{len(files)}")
    print(f"知识库总字符数：{total_chars}")
    print(f"知识库路径：{KNOWLEDGE_DIR}")


if __name__ == "__main__":
    main()
